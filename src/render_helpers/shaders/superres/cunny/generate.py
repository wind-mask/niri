#!/usr/bin/env python3
"""Writes the GLSL shaders for the CuNNy networks that niri runs.

The networks are read out of the effects that ship them with `extract.py`, and this turns each
convolution pass into a fragment shader. See `extract.py` for where the reference comes from and
what the passes look like.

Things that the port has to do differently, all of them on purpose:

- The reference is a compute shader that writes several textures at once. smithay's renderer has no
  multiple render targets, so a pass that produces twelve channels is written three times, once per
  group of four, each re-reading the same neighbourhoods. The arithmetic is unchanged; only the
  texture reads are repeated, and they are a small part of a pass that is dominated by the weights.
- The reference accumulates in `min16float`. These shaders accumulate in `highp` and quantize where
  the reference does, in the eight-bit textures between passes, which is where the quantization
  that matters to the result happens.
- The reference keeps nine taps of four textures in registers. These shaders gather the
  neighbourhood of one texture at a time and accumulate, so that a driver with a small register
  file still compiles them.
- The reference multiplies a `vec4` of channels by an `M4` of weights, which is four dot products.
  These shaders write those four dot products out, so there is no matrix layout to get wrong.
- smithay's texture programs bind one sampler, named `tex`. Passes that read more than one texture
  bind the others themselves, to texture units 1 and 2, and set the sampler uniforms to those units
  as plain integers -- a sampler uniform is just a number. See superres.rs.

The last pass, the pixel shuffle, is not written here: its structure is the port's own, since a
compositor has to handle the chroma and the alpha itself.
"""

import os
import sys

from extract import parse


def emit_shader(variant, slug, pass_, out_dir):
    """Writes one shader per group of four output channels."""
    for acc in sorted(pass_["out_texture"]):
        name = f"pass{pass_['num']}_a{acc}.frag"
        text = emit_accumulator(variant, pass_, acc)
        with open(os.path.join(out_dir, name), "w") as f:
            f.write(text)
        print(f"wrote {slug}/{name}")


def emit_accumulator(variant, pass_, acc):
    """Writes the shader that produces the four channels of one accumulator."""
    inputs = len(pass_["inputs"])
    bias = pass_["biases"].get(acc, [0.0] * 4)
    relu = acc in pass_["relu"]
    weights = pass_["weights"]

    rv = []
    rv.append("#version 100")
    rv.append("")
    rv.append("//_DEFINES_")
    rv.append("")
    rv.append(
        f"// CuNNy {variant}, pass {pass_['num']} ({pass_['desc']}), output channels {acc * 4}..{acc * 4 + 3}."
    )
    rv.append("//")
    rv.append("// Generated by src/render_helpers/shaders/superres/cunny/generate.py, from the")
    rv.append("// Magpie effect of https://github.com/Blinue/CuNNy (commit dc3f51aa, GPL-3.0), whose")
    rv.append("// weights are trained by https://github.com/funnyplanter/CuNNy. Do not edit this")
    rv.append("// file: change the generator or the effect instead.")
    rv.append("//")
    rv.append("// See the generator's docstring for what the port does differently from the")
    rv.append("// reference, and superres.rs for how the passes are run and cached.")
    rv.append("")
    rv.append("precision highp float;")
    rv.append("")
    # The first pass reads the client buffer, whose size is the window's, not the size of the rect
    # being resampled: `v_coords` is in its texel space already, the way the resampling shaders use
    # it, with the crop and the buffer's transform folded in by the renderer's vertex shader. The
    # other passes read the network's own textures, which are exactly the source rect.
    client = pass_["inputs"] == ["INPUT"]

    rv.append("uniform sampler2D tex;")
    for i in range(1, inputs):
        rv.append(f"uniform sampler2D niri_tex{i};")
    if client:
        rv.append("// Size of the client buffer in texels, and the rect of it being resampled.")
        rv.append("uniform vec2 niri_tex_size;")
        rv.append("uniform vec4 niri_src_rect;")
    else:
        rv.append("// Size of every input texture in texels.")
        rv.append("uniform vec2 niri_size;")
    rv.append("varying vec2 v_coords;")
    rv.append("")

    # The reference samples exact texel centers, with out-of-range taps clamping to the edge.
    rv.append("// Samples the neighboring texel `off` from the center of the current one.")
    for i in range(inputs):
        sampler = "tex" if i == 0 else f"niri_tex{i}"
        rv.append(f"vec4 niri_tap{i}(vec2 pos, vec2 off) {{")
        if client:
            rv.append("    vec2 lo = niri_src_rect.xy + vec2(0.5);")
            rv.append("    vec2 hi = niri_src_rect.xy + niri_src_rect.zw - vec2(0.5);")
            rv.append("    vec2 t = clamp(pos + off, lo, hi);")
            rv.append("    vec4 c = texture2D(tex, t / niri_tex_size);")
            rv.append("    vec3 rgb = c.a > 0.0 ? c.rgb / c.a : c.rgb;")
            rv.append("    return vec4(rgb, c.a);")
        else:
            rv.append("    vec2 t = clamp(pos + off, vec2(0.5), niri_size - vec2(0.5));")
            rv.append(f"    return texture2D({sampler}, t / niri_size);")
        rv.append("}")
    if pass_["luma"]:
        rv.append("")
        rv.append("// Rec.601 luma, which is all that the input layer of this network sees.")
        rv.append("float niri_luma(vec2 pos) {")
        rv.append("    vec2 lo = niri_src_rect.xy + vec2(0.5);")
        rv.append("    vec2 hi = niri_src_rect.xy + niri_src_rect.zw - vec2(0.5);")
        rv.append("    vec2 t = clamp(pos, lo, hi);")
        rv.append("    vec4 c = texture2D(tex, t / niri_tex_size);")
        rv.append("    vec3 rgb = c.a > 0.0 ? c.rgb / c.a : c.rgb;")
        rv.append("    return dot(vec3(" + ", ".join(f"{v:.6}" for v in pass_["luma"]) + "),")
        rv.append("               rgb);")
        rv.append("}")
    rv.append("")

    # The weights: for each input texture and tap, four dot products, one per output channel.
    rv.append("// Weights of the four output channels, per input texture and 3x3 tap.")
    for i in range(inputs):
        for tap in range(9):
            for lane in range(4):
                per_channel = weights.get((acc, lane), {})
                values = [per_channel.get((i * 4 + c, tap), 0.0) for c in range(4)]
                rv.append(
                    f"const vec4 niri_w{i}_{tap}_{lane} = vec4({fmt(values)});  // output channel {lane}"
                )
        rv.append("")

    rv.append("void main() {")
    if client:
        rv.append("    vec2 pos = v_coords * niri_tex_size;")
    else:
        rv.append("    vec2 pos = floor(v_coords * niri_size) + vec2(0.5);")
    rv.append(f"    vec4 acc = vec4({fmt(bias)});")
    rv.append("")

    # Every tap gets its own block: a shading language does not let a name be declared twice in
    # the same scope, and packing them together is a mistake that some drivers accept and others
    # refuse.
    for i in range(inputs):
        for tap in range(9):
            dx, dy = (tap % 3) - 1, (tap // 3) - 1
            rv.append("    {")
            if pass_["luma"]:
                rv.append(f"        float s = niri_luma(pos + vec2({dx}.0, {dy}.0));")
                rv.append(f"        acc += vec4(niri_w{i}_{tap}_0.x, niri_w{i}_{tap}_1.x,")
                rv.append(f"                    niri_w{i}_{tap}_2.x, niri_w{i}_{tap}_3.x) * s;")
            else:
                rv.append(f"        vec4 s = niri_tap{i}(pos, vec2({dx}.0, {dy}.0));")
                rv.append(f"        acc += vec4(dot(niri_w{i}_{tap}_0, s), dot(niri_w{i}_{tap}_1, s),")
                rv.append(f"                    dot(niri_w{i}_{tap}_2, s), dot(niri_w{i}_{tap}_3, s));")
            rv.append("    }")
        rv.append("")

    if relu:
        rv.append("    // The hidden layers are ReLU.")
        rv.append("    acc = max(acc, vec4(0.0));")
    rv.append("    gl_FragColor = acc;")
    rv.append("}")
    rv.append("")
    return "\n".join(rv)


def emit_shuffle(variant, pass_, out_dir):
    """Writes the pixel shuffle, whose structure the port owns.

    The reference draws a 2x2 block of output pixels per thread, one sub-pixel of the upscaled image
    each, and adds a luma residual that it computed for all four of them. A fragment shader cannot
    do that: which sub-pixel a fragment is depends on its position, and picking the weights of a
    sub-pixel needs a constant index into them, so the four cases would have to be branches, and
    neighbouring fragments always take different branches -- a whole warp would run all four and pay
    four times over, which is more than the rest of the network.

    So this writes the four residuals of one *source* texel into the four channels of one output
    texel instead, at the source resolution: the arithmetic is the reference's, exactly, with no
    branches and no wasted lanes. The final draw upscales that, and is the only place that knows how
    the residuals line up with the destination's pixels.
    """
    inputs = len(pass_["inputs"]) - 1  # without the client buffer
    weights = pass_["weights"]
    luma_rgb = (0.299, 0.587, 0.114)
    rgb_shuffle = (1, 0) in weights
    if rgb_shuffle:
        bias = [
            sum(luma_rgb[ch] * pass_["biases"].get(ch, [0.0] * 4)[lane] for ch in range(3))
            for lane in range(4)
        ]
    else:
        bias = pass_["biases"].get(0, [0.0] * 4)

    rv = []
    rv.append("#version 100")
    rv.append("")
    rv.append("//_DEFINES_")
    rv.append("")
    rv.append(f"// CuNNy {variant}, pass {pass_['num']} ({pass_['desc']}): the pixel shuffle's")
    rv.append("// residuals, one source texel per fragment, four sub-pixels per texel.")
    rv.append("//")
    rv.append("// Generated by src/render_helpers/shaders/superres/cunny/generate.py, from the")
    rv.append("// Magpie effect of https://github.com/Blinue/CuNNy (commit dc3f51aa, GPL-3.0), whose")
    rv.append("// weights are trained by https://github.com/funnyplanter/CuNNy. Do not edit this")
    rv.append("// file: change the generator or the effect instead.")
    rv.append("//")
    rv.append("// The channels are the four sub-pixels of the doubled image, in the order the")
    rv.append("// reference's r0.x, r0.y, r0.z, r0.w use: (0,0), (1,0), (0,1), (1,1). What comes out")
    rv.append("// is a luma residual per sub-pixel; the chroma and the alpha are the client buffer's")
    rv.append("// own, which is the next shader's business.")
    rv.append("")
    rv.append("precision highp float;")
    rv.append("")
    # The first input is the one the pass draws, so the renderer binds it as `tex`; the rest are
    # bound to the texture units after it. This is the same convention the convolution passes use,
    # and it has to be: the runtime names the uniforms for both.
    rv.append("uniform sampler2D tex;")
    for i in range(1, inputs):
        rv.append(f"uniform sampler2D niri_tex{i};")
    rv.append("// Size of the source in texels.")
    rv.append("uniform vec2 niri_src_size;")
    rv.append("varying vec2 v_coords;")
    rv.append("")

    rv.append("// The nine-tap neighborhood of a source texel, clamped to the source.")
    for i in range(inputs):
        rv.append(f"vec4 niri_f{i}(vec2 pos, vec2 off) {{")
        rv.append("    vec2 t = clamp(pos + off, vec2(0.0), niri_src_size - vec2(1.0));")
        sampler = "tex" if i == 0 else f"niri_tex{i}"
        rv.append(f"    return texture2D({sampler}, (t + vec2(0.5)) / niri_src_size);")
        rv.append("}")
    rv.append("")

    # One vec4 of weights per sub-pixel, input texture and tap: the four input channels of a
    # texture's texel, and what each of them contributes to that sub-pixel.
    rv.append("// Weights of the four sub-pixels, per input texture and 3x3 tap.")
    for lane in range(4):
        for i in range(inputs):
            for tap in range(9):
                if rgb_shuffle:
                    values = [
                        sum(
                            luma_rgb[ch] * weights.get((ch, lane), {}).get((i * 4 + c, tap), 0.0)
                            for ch in range(3)
                        )
                        for c in range(4)
                    ]
                else:
                    per_channel = weights.get((0, lane), {})
                    values = [per_channel.get((i * 4 + c, tap), 0.0) for c in range(4)]
                rv.append(
                    f"const vec4 niri_s{lane}_{i}_{tap} = vec4({fmt(values)});  // sub-pixel {lane}"
                )
        rv.append("")

    rv.append("void main() {")
    rv.append("    vec2 pos = floor(v_coords * niri_src_size);")
    rv.append(f"    vec4 acc = vec4({fmt(bias)});")
    rv.append("")

    for i in range(inputs):
        for tap in range(9):
            dx, dy = (tap % 3) - 1, (tap // 3) - 1
            rv.append("    {")
            rv.append(f"        vec4 s = niri_f{i}(pos, vec2({dx}.0, {dy}.0));")
            rv.append(f"        acc += vec4(dot(niri_s0_{i}_{tap}, s), dot(niri_s1_{i}_{tap}, s),")
            rv.append(f"                    dot(niri_s2_{i}_{tap}, s), dot(niri_s3_{i}_{tap}, s));")
            rv.append("    }")
        rv.append("")

    rv.append("    gl_FragColor = acc;")
    rv.append("}")
    rv.append("")
    return "\n".join(rv)


def fmt(values):
    return ", ".join(f"{v:.8}" for v in values)


def main(reference, out_dir):
    for effect, variant, slug in (
        ("CuNNy-fast-NVL.hlsl", "fast-NVL", "fast"),
        ("CuNNy-3x12-NVL.hlsl", "3x12-NVL", "3x12"),
    ):
        passes = parse(os.path.join(reference, effect))
        print(f"{slug}: {len(passes)} passes")
        variant_dir = os.path.join(out_dir, slug)
        os.makedirs(variant_dir, exist_ok=True)
        for p in passes[:-1]:
            emit_shader(variant, slug, p, variant_dir)
        shuffle = emit_shuffle(variant, passes[-1], variant_dir)
        with open(os.path.join(variant_dir, "shuffle.frag"), "w") as f:
            f.write(shuffle)
        print(f"wrote {slug}/shuffle.frag")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
